#!/usr/bin/env node
/**
 * Bake environment variables into public/config.js before deployment.
 * Usage: SUPABASE_URL=... SUPABASE_ANON_KEY=... SITE_URL=... node scripts/build.mjs
 * (reads process.env first, then a local .env file if present)
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";

const root = new URL("..", import.meta.url).pathname;

function loadDotEnv() {
  const p = root + ".env";
  if (!existsSync(p)) return;
  for (const line of readFileSync(p, "utf8").split("\n")) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
    if (m && !process.env[m[1]]) process.env[m[1]] = m[2].replace(/^["']|["']$/g, "");
  }
}
loadDotEnv();

const required = ["SUPABASE_URL", "SUPABASE_ANON_KEY"];
for (const k of required) {
  if (!process.env[k]) {
    console.warn(`[build] warning: ${k} is not set; leaving config value empty (demo mode).`);
  }
}

const cfg = `/**
 * AUTO-GENERATED by scripts/build.mjs — do not edit by hand in CI.
 * Public values only (anon key is a public identifier; security is enforced
 * by database RLS). service_role must never appear here.
 */
window.APP_CONFIG = {
  SUPABASE_URL: ${JSON.stringify(process.env.SUPABASE_URL ?? "")},
  SUPABASE_ANON_KEY: ${JSON.stringify(process.env.SUPABASE_ANON_KEY ?? "")},
  SITE_URL: ${JSON.stringify(process.env.SITE_URL ?? "")},
};
`;

writeFileSync(root + "public/config.js", cfg);
console.log("[build] public/config.js written.");
