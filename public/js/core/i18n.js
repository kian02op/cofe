let current = "fa";

export function setLang(lang) {
  current = dicts[lang] ? lang : "fa";
  return current;
}
export function getLang() {
  return current;
}

/** Translate key with {placeholder} interpolation. Falls back to fa then key. */
export function t(key, params) {
  let s = dicts[current]?.[key] ?? dicts.fa[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, String(v));
  }
  return s;
}

export function applyDocumentLang(lang) {
  const d = dicts[lang] ? lang : "fa";
  document.documentElement.lang = d;
  document.documentElement.dir = dicts[d].dir;
}
